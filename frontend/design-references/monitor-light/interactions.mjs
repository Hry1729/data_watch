assert.ok(Math.abs(panels[0].h-panels[1].h)<1)
assert.equal(await ev("Array.from(document.querySelectorAll('.kpi-icon')).every(e=>getComputedStyle(e).backgroundColor==='rgba(0, 0, 0, 0)')"),true)
assert.equal(await ev("document.querySelectorAll('.alarm-legend button').length"),3)
