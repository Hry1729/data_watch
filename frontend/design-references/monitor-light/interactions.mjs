import fs from 'node:fs/promises'
import assert from 'node:assert/strict'
const targets=await fetch('http://127.0.0.1:9227/json').then(r=>r.json())
const ws=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl)
await new Promise(r=>ws.addEventListener('open',r,{once:true}))
let id=0;const pending=new Map();const errors=[]
ws.addEventListener('message',e=>{const m=JSON.parse(e.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p?.reject(m.error):p?.resolve(m.result)}else if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails)})
const call=(method,params={})=>new Promise((resolve,reject)=>{pending.set(++id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))})
const ev=async expression=>(await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true})).result?.value
const pause=ms=>new Promise(r=>setTimeout(r,ms))
const shot=async name=>{const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:true});await fs.writeFile('frontend/design-references/monitor-light/'+name+'.png',Buffer.from(r.data,'base64'))}
await call('Runtime.enable')
const panels=await ev("Array.from(document.querySelectorAll('.floating')).map(e=>({w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height}))")
