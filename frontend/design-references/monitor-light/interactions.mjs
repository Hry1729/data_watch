assert.equal(await ev("Array.from(document.querySelectorAll('.module')).every(x=>x.classList.contains('unknown'))"),true)
await shot('unavailable')
await ev("window.qaMode='empty';document.querySelector('[aria-label=刷新数据]').click()")
await pause(350)
assert.equal(await ev("document.querySelector('.kpi strong').textContent"),'0')
assert.equal(await ev("document.body.innerText.includes('今日暂无日志')"),true)
await shot('empty')
await ev("window.qaMode='normal';document.querySelector('[aria-label=刷新数据]').click()")
await pause(350)
await call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
await pause(100)
assert.equal(await ev("getComputedStyle(document.querySelector('.module.warning .module-state i')).animationName"),'none')
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false})
await pause(300)
await shot('desktop-1280')
