@dataclass(slots=True)
class MenuPayload:
    name: str
    path: str
    component: str
    title_key: str
    icon: str = ""
    parent_id: int | None = None
    menu_type: str = "menu"
    link: str = ""
    is_iframe: bool = False
    keep_alive: bool = False
    is_hide: bool = False
    is_hide_tab: bool = False
    fixed_tab: bool = False
    active_path: str = ""
    is_full_page: bool = False
    sort: int = 1
    enabled: bool = True

    @classmethod
    def from_dict(cls, payload: dict[str, Any]) -> "MenuPayload":
        name = str(payload.get("name") or "").strip()
        title_key = str(payload.get("titleKey") or payload.get("title_key") or payload.get("meta", {}).get("title") or "").strip()
        path = str(payload.get("path") or "").strip()
        component = str(payload.get("component") or "").strip()
        if not name or not title_key:
            raise ApiError(400, "name and titleKey are required")
        parent_raw = payload.get("parentId") if "parentId" in payload else payload.get("parent_id")
        parent_id = int(parent_raw) if parent_raw not in (None, "") else None
        return cls(
            name=name,
            path=path,
            component=component,
            title_key=title_key,
            icon=str(payload.get("icon") or payload.get("meta", {}).get("icon") or "").strip(),
            parent_id=parent_id,
            menu_type=str(payload.get("menuType") or payload.get("menu_type") or "menu").strip() or "menu",
            link=str(payload.get("link") or "").strip(),
            is_iframe=_coerce_bool(payload.get("isIframe", payload.get("is_iframe")), default=False),
            keep_alive=_coerce_bool(payload.get("keepAlive", payload.get("keep_alive")), default=False),
            is_hide=_coerce_bool(payload.get("isHide", payload.get("is_hide")), default=False),
            is_hide_tab=_coerce_bool(payload.get("isHideTab", payload.get("is_hide_tab")), default=False),
            fixed_tab=_coerce_bool(payload.get("fixedTab", payload.get("fixed_tab")), default=False),
            active_path=str(payload.get("activePath") or payload.get("active_path") or "").strip(),
            is_full_page=_coerce_bool(payload.get("isFullPage", payload.get("is_full_page")), default=False),
            sort=int(payload.get("sort") or 1),
            enabled=_coerce_bool(payload.get("enabled"), default=True),
        )


