		private void button1_Click(object sender, EventArgs e)
		{
			if (!IPAddress.TryParse(textBox1.Text, out var _))
			{
				DemoUtils.ShowMessage(DemoUtils.IpAddressInputWrong);
				return;
			}
			if (!int.TryParse(textBox2.Text, out var result))
			{
				DemoUtils.ShowMessage(DemoUtils.PortInputWrong);
				return;
			}
			if (!byte.TryParse(textBox15.Text, out var result2))
			{
				DemoUtils.ShowMessage("Station input is wrong！");
				return;
			}
			busTcpClient?.ConnectClose();
			busTcpClient = new DcsNanJingAuto(textBox1.Text, result, result2);
			busTcpClient.AddressStartWithZero = checkBox1.Checked;
			ComboBox1_SelectedIndexChanged(null, new EventArgs());
			busTcpClient.IsStringReverse = checkBox3.Checked;
			try
			{
				OperateResult operateResult = busTcpClient.ConnectServer();
				if (operateResult.IsSuccess)
				{
					DemoUtils.ShowMessage(StringResources.Language.ConnectedSuccess);
					button2.Enabled = true;
					button1.Enabled = false;
					panel2.Enabled = true;
					userControlReadWriteDevice1.SetReadWriteNet(busTcpClient, "100", true);
					userControlReadWriteDevice1.BatchRead.SetReadWriteNet(busTcpClient, "100", string.Empty);
					userControlReadWriteDevice1.MessageRead.SetReadSourceBytes((byte[] m) => busTcpClient.ReadFromCoreServer(m, true, false), string.Empty, string.Empty);
					control.SetDevice(busTcpClient, "100");
				}
				else
				{
					DemoUtils.ShowMessage(StringResources.Language.ConnectedFailed + operateResult.Message + Environment.NewLine + "Error: " + operateResult.ErrorCode);
				}
			}
			catch (Exception ex)
			{
				DemoUtils.ShowMessage(ex.Message);
			}
		}

		private void button2_Click(object sender, EventArgs e)
		{
			busTcpClient.ConnectClose();
			button2.Enabled = false;
			button1.Enabled = true;
			panel2.Enabled = false;
		}

